/**
 * The icons the app draws, inline.
 *
 * A handful of glyphs do not earn a package, a font and a build step, so each
 * icon is one `<svg>` holding one path. Every icon draws in `currentColor` and is
 * hidden from a screen reader: the control beside it carries the name.
 *
 * This file is the precedent for every icon after it. Add the path, not a
 * dependency.
 *
 * Paths: Font Awesome Free 6, regular style, or solid where the free set has
 * no regular glyph, and the brands set for the marks of the services a client
 * link points at. CC BY 4.0 (https://fontawesome.com/license/free).
 */

/**
 * What a caller may say about an icon: its size and motion, as classes. The
 * default is the size every icon drew before, beside a line of text.
 */
export type IconProps = { className?: string };

/** The size an icon draws at when the caller names none. */
const ICON_SIZE = "size-3.5";

/**
 * The frame every icon shares: the box Font Awesome draws in, and its size.
 * Every glyph is 512 tall; `width` is the glyph's own, and the glyph centres.
 */
function Icon({ path, width = 448, className = ICON_SIZE }: { path: string; width?: number; className?: string }) {
  return (
    <svg
      viewBox={`0 0 ${width} 512`}
      aria-hidden="true"
      fill="currentColor"
      className={`inline-block shrink-0 ${className}`}
    >
      <path d={path} />
    </svg>
  );
}

